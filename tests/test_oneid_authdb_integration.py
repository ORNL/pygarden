"""PostgreSQL integration coverage for the OneID identity schema upgrade."""

# This integration test focuses on schema behavior and uses a compact imperative fixture.
# ruff: noqa: D103

import asyncio
import os
from uuid import uuid4

import psycopg
import pytest


@pytest.mark.integration
@pytest.mark.skipif(
    os.getenv("ESDX_RUN_INTEGRATION") != "1",
    reason="requires local Compose PostgreSQL",
)
def test_identity_schema_upgrade_preserves_unlinked_email_accounts(monkeypatch):
    """Add stable identity mapping without auto-linking an existing account by email."""
    from pygarden.api.oneid import auth_db, config

    schema = f"oidc_test_{uuid4().hex[:12]}"
    table = "legacy_users"
    identity_table = "external_identities"
    host = os.getenv("ESDX_TEST_PG_HOST", "127.0.0.1")
    port = int(os.getenv("ESDX_TEST_PG_PORT", "5433"))
    database = os.getenv("ESDX_TEST_PG_DATABASE", "esdx")
    user_name = os.getenv("ESDX_TEST_PG_USER", "esdx")
    password = os.getenv("ESDX_TEST_PG_PASSWORD", "esdx-local-password")

    with psycopg.connect(host=host, port=port, dbname=database, user=user_name, password=password) as connection:
        connection.execute(f'CREATE SCHEMA "{schema}"')
        connection.execute(
            f'''CREATE TABLE "{schema}"."{table}" (
                user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                first_name TEXT NOT NULL,
                last_name TEXT NOT NULL,
                email TEXT UNIQUE,
                us_citizen BOOLEAN NOT NULL DEFAULT FALSE,
                affiliation TEXT NOT NULL DEFAULT '',
                approved BOOLEAN NOT NULL DEFAULT FALSE,
                enabled BOOLEAN NOT NULL DEFAULT TRUE,
                admin BOOLEAN NOT NULL DEFAULT FALSE,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
            )'''
        )
        old_id = connection.execute(
            f'''INSERT INTO "{schema}"."{table}"
                (first_name,last_name,email) VALUES('Legacy','Researcher',%s) RETURNING user_id''',
            ("researcher@example.invalid",),
        ).fetchone()[0]

    monkeypatch.setattr(config, "AUTH_DB_SCHEMA", schema)
    monkeypatch.setattr(config, "AUTH_USERS_TABLE", table)
    monkeypatch.setattr(config, "AUTH_IDENTITIES_TABLE", identity_table)
    monkeypatch.setattr(auth_db, "_U", auth_db._qualified_name(schema, table))
    monkeypatch.setattr(auth_db, "_I", auth_db._qualified_name(schema, identity_table))
    connection_info = auth_db.AuthDB.create_connection_info(
        db_name=database,
        db_user=user_name,
        db_password=password,
        db_host=host,
        db_port=port,
        db_schema=schema,
        db_timeout=10,
    )

    async def apply_upgrade_and_provision():
        database_api = auth_db.AuthDB(connection_info=connection_info)
        await database_api.open()
        try:
            await database_api.upgrade_identity_schema()
            return await database_api.create_user_for_identity(
                issuer="https://issuer.example.invalid",
                subject="verified-subject",
                email="researcher@example.invalid",
                first_name="Verified",
                last_name="Researcher",
            )
        finally:
            await database_api.close()

    try:
        provisioned = asyncio.run(apply_upgrade_and_provision())
        with psycopg.connect(host=host, port=port, dbname=database, user=user_name, password=password) as connection:
            legacy_constraints = connection.execute(
                """SELECT COUNT(*) FROM pg_constraint
                   WHERE conrelid=to_regclass(%s) AND contype='u'""",
                (f"{schema}.{table}",),
            ).fetchone()[0]
            mapping = connection.execute(
                f'''SELECT user_id FROM "{schema}"."{identity_table}"
                    WHERE issuer=%s AND subject=%s''',
                ("https://issuer.example.invalid", "verified-subject"),
            ).fetchone()
            assert legacy_constraints == 0
            assert mapping == (provisioned[config.COL_USER_ID],)
            assert mapping[0] != old_id
            assert provisioned[config.COL_ADMIN] is False
    finally:
        with psycopg.connect(host=host, port=port, dbname=database, user=user_name, password=password) as connection:
            connection.execute(f'DROP SCHEMA IF EXISTS "{schema}" CASCADE')
