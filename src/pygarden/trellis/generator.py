"""Database introspection and deterministic Trellis generation."""

# ruff: noqa: E501

from __future__ import annotations

import keyword
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from pygarden.trellis.config import TableConfig, TrellisConfig
from pygarden.trellis.exceptions import TrellisGenerationError

PY_MARKER = "# Generated by pyGARDEN Trellis. DO NOT EDIT."
SQL_MARKER = "-- Generated by pyGARDEN Trellis. DO NOT EDIT."


@dataclass(frozen=True)
class Column:
    """An introspected database column."""

    name: str
    data_type: str
    udt_name: str
    nullable: bool
    default: str | None
    identity: bool
    generated: bool
    primary_key: bool
    ordinal: int


@dataclass(frozen=True)
class Relation:
    """An introspected table or view."""

    config: TableConfig
    columns: tuple[Column, ...]
    kind: str

    @property
    def writable(self) -> bool:
        """Return whether CRUD writes may be generated for the relation."""
        return self.kind in {"BASE TABLE", "FOREIGN", "FOREIGN TABLE"}


class PostgresIntrospector:
    """Read relation metadata from PostgreSQL catalogs."""

    def __init__(self, connection: Any):
        """Create an introspector for an asyncpg-compatible connection."""
        self.connection = connection

    async def inspect(self, table: TableConfig) -> Relation:
        """Inspect one configured table or view."""
        relation = await self.connection.fetchrow(
            """SELECT table_type FROM information_schema.tables
               WHERE table_schema=$1 AND table_name=$2
               UNION ALL SELECT 'VIEW' FROM information_schema.views
               WHERE table_schema=$1 AND table_name=$2 LIMIT 1""",
            table.schema,
            table.table,
        )
        if relation is None:
            raise TrellisGenerationError(f"Relation does not exist: {table.schema}.{table.table}")
        rows = await self.connection.fetch(
            """SELECT c.column_name, c.data_type, c.udt_name, c.is_nullable,
                      c.column_default, c.is_identity, c.is_generated, c.ordinal_position,
                      EXISTS (
                        SELECT 1 FROM information_schema.table_constraints tc
                        JOIN information_schema.key_column_usage kcu
                          ON tc.constraint_name=kcu.constraint_name
                         AND tc.constraint_schema=kcu.constraint_schema
                        WHERE tc.constraint_type='PRIMARY KEY'
                          AND tc.table_schema=c.table_schema AND tc.table_name=c.table_name
                          AND kcu.column_name=c.column_name
                      ) AS primary_key
               FROM information_schema.columns c
               WHERE c.table_schema=$1 AND c.table_name=$2 ORDER BY c.ordinal_position""",
            table.schema,
            table.table,
        )
        if not rows:
            raise TrellisGenerationError(f"No columns found for {table.schema}.{table.table}")
        columns = tuple(
            Column(
                row["column_name"],
                row["data_type"],
                row["udt_name"],
                row["is_nullable"] == "YES",
                row["column_default"],
                row["is_identity"] == "YES",
                row["is_generated"] != "NEVER",
                bool(row["primary_key"]),
                int(row["ordinal_position"]),
            )
            for row in rows
        )
        kind = relation["table_type"] if hasattr(relation, "keys") else relation[0]
        return Relation(table, columns, str(kind))


class MSSQLIntrospector:
    """Read relation metadata from Microsoft SQL Server catalogs."""

    def __init__(self, executor: Any):
        """Create an introspector for a Trellis MSSQL executor."""
        self.executor = executor

    async def inspect(self, table: TableConfig) -> Relation:
        """Inspect one configured SQL Server table or view."""
        relation = await self.executor.fetchrow(
            """SELECT TABLE_TYPE AS table_type
               FROM INFORMATION_SCHEMA.TABLES
               WHERE TABLE_SCHEMA=? AND TABLE_NAME=?""",
            table.schema,
            table.table,
        )
        if relation is None:
            raise TrellisGenerationError(f"Relation does not exist: {table.schema}.{table.table}")
        rows = await self.executor.fetch(
            """SELECT c.COLUMN_NAME AS column_name, c.DATA_TYPE AS data_type,
                      c.DATA_TYPE AS udt_name, c.IS_NULLABLE AS is_nullable,
                      c.COLUMN_DEFAULT AS column_default, c.ORDINAL_POSITION AS ordinal_position,
                      CONVERT(bit, COLUMNPROPERTY(
                          OBJECT_ID(QUOTENAME(c.TABLE_SCHEMA) + '.' + QUOTENAME(c.TABLE_NAME)),
                          c.COLUMN_NAME, 'IsIdentity')) AS is_identity,
                      CONVERT(bit, COLUMNPROPERTY(
                          OBJECT_ID(QUOTENAME(c.TABLE_SCHEMA) + '.' + QUOTENAME(c.TABLE_NAME)),
                          c.COLUMN_NAME, 'IsComputed')) AS is_generated,
                      CONVERT(bit, CASE WHEN EXISTS (
                        SELECT 1 FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS tc
                        JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE kcu
                          ON tc.CONSTRAINT_NAME=kcu.CONSTRAINT_NAME
                         AND tc.CONSTRAINT_SCHEMA=kcu.CONSTRAINT_SCHEMA
                        WHERE tc.CONSTRAINT_TYPE='PRIMARY KEY'
                          AND tc.TABLE_SCHEMA=c.TABLE_SCHEMA AND tc.TABLE_NAME=c.TABLE_NAME
                          AND kcu.COLUMN_NAME=c.COLUMN_NAME
                      ) THEN 1 ELSE 0 END) AS primary_key
               FROM INFORMATION_SCHEMA.COLUMNS c
               WHERE c.TABLE_SCHEMA=? AND c.TABLE_NAME=?
               ORDER BY c.ORDINAL_POSITION""",
            table.schema,
            table.table,
        )
        if not rows:
            raise TrellisGenerationError(f"No columns found for {table.schema}.{table.table}")
        columns = tuple(
            Column(
                row["column_name"],
                row["data_type"],
                "rowversion" if row["udt_name"] == "timestamp" else row["udt_name"],
                row["is_nullable"] == "YES",
                row["column_default"],
                bool(row["is_identity"]),
                bool(row["is_generated"]),
                bool(row["primary_key"]),
                int(row["ordinal_position"]),
            )
            for row in rows
        )
        return Relation(table, columns, str(relation["table_type"]))


